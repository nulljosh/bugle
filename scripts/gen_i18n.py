#!/usr/bin/env python3
"""Writes web/i18n.js from the apps' String Catalog plus the few strings only the web reader has, so the web and
the apps say the same thing in every language. Run after changing ios/Sources/Shared/Localizable.xcstrings."""
import json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
L = ["es", "fr", "de", "pt-BR", "ja", "zh-Hans"]
cat = json.loads((root / "ios/Sources/Shared/Localizable.xcstrings").read_text())
table = {k: [v["localizations"][l]["stringUnit"]["value"] for l in L] for k, v in cat["strings"].items()}
WEB = {
    "Forgot password?": ["¿Olvidaste la contraseña?", "Mot de passe oublié ?", "Passwort vergessen?", "Esqueceu a senha?", "パスワードをお忘れですか？", "忘记密码？"],
    "Tap a feed to read only it. Swipe left to remove it.": ["Toca un feed para leer solo ese. Desliza a la izquierda para quitarlo.", "Touchez un flux pour ne lire que lui. Balayez vers la gauche pour le retirer.", "Tippe auf einen Feed, um nur ihn zu lesen. Nach links wischen entfernt ihn.", "Toque em um feed para ler só ele. Deslize para a esquerda para removê-lo.", "フィードをタップするとそれだけを読めます。左にスワイプで削除。", "轻点订阅源即可只读它。向左轻扫可移除。"],
    "Loading…": ["Cargando…", "Chargement…", "Wird geladen…", "Carregando…", "読み込み中…", "正在载入…"],
    "Sections": ["Secciones", "Sections", "Bereiche", "Seções", "セクション", "版块"],
    "Back": ["Atrás", "Retour", "Zurück", "Voltar", "戻る", "返回"],
    "Share": ["Compartir", "Partager", "Teilen", "Compartilhar", "共有", "分享"],
    "Larger text": ["Texto más grande", "Texte plus grand", "Größerer Text", "Texto maior", "文字を大きく", "放大文字"],
    "Smaller text": ["Texto más pequeño", "Texte plus petit", "Kleinerer Text", "Texto menor", "文字を小さく", "缩小文字"],
    "Open in browser": ["Abrir en el navegador", "Ouvrir dans le navigateur", "Im Browser öffnen", "Abrir no navegador", "ブラウザで開く", "在浏览器中打开"],
    "Password": ["Contraseña", "Mot de passe", "Passwort", "Senha", "パスワード", "密码"],
    "Blindspots": ["Puntos ciegos", "Angles morts", "Blinde Flecken", "Pontos cegos", "死角", "盲点"],
    "Not following anything yet.": ["Aún no sigues nada.", "Aucun abonnement pour l'instant.", "Du folgst noch nichts.", "Você ainda não segue nada.", "まだ何もフォローしていません。", "还没有关注任何内容。"],
    "Open original": ["Abrir el original", "Ouvrir l'original", "Original öffnen", "Abrir o original", "元の記事を開く", "打开原文"],
}
table.update(WEB)
js = f"""// Generated by scripts/gen_i18n.py from the apps' String Catalog; do not edit by hand.
// The reader is written in English. For a visitor whose browser asks for one of these languages, every text and label
// that exactly matches a key is swapped, now and as the reader adds more. Headlines never match a key.
(function () {{
  var langs = {json.dumps(L)};
  var pick = (navigator.languages || [navigator.language]).map(function (l) {{
    return /^zh/i.test(l) ? 'zh-Hans' : /^pt/i.test(l) ? 'pt-BR' : l.slice(0, 2).toLowerCase();
  }}).find(function (l) {{ return langs.indexOf(l) >= 0; }});
  if (!pick) return;
  var col = langs.indexOf(pick), T = {json.dumps(table, ensure_ascii=False, separators=(',', ':'))};
  var one = function (s) {{ var k = s.trim(), row = T[k]; return row ? s.replace(k, row[col]) : s; }};
  // "Leans left · Canadian public broadcaster": each piece on its own
  var tr = function (s) {{ return s.indexOf(' · ') < 0 ? one(s) : s.split(' · ').map(one).join(' · '); }};
  function walk(root) {{
    var w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT), n;
    while ((n = w.nextNode())) {{ var v = tr(n.nodeValue); if (v !== n.nodeValue) n.nodeValue = v; }}
    if (root.querySelectorAll) [root].concat(Array.prototype.slice.call(root.querySelectorAll('[placeholder],[aria-label]'))).forEach(function (e) {{
      ['placeholder', 'aria-label'].forEach(function (a) {{ var v = e.getAttribute && e.getAttribute(a); if (v && tr(v) !== v) e.setAttribute(a, tr(v)); }});
    }});
  }}
  document.documentElement.lang = pick;
  walk(document.body);
  new MutationObserver(function (list) {{
    list.forEach(function (m) {{ m.addedNodes.forEach(function (n) {{ if (n.nodeType === 3) {{ var v = tr(n.nodeValue); if (v !== n.nodeValue) n.nodeValue = v; }} else if (n.nodeType === 1) walk(n); }}); }});
  }}).observe(document.body, {{ childList: true, subtree: true }});
}})();
"""
(root / "web/i18n.js").write_text(js)
print(len(table), "strings")
