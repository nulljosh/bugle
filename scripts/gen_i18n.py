#!/usr/bin/env python3
"""Writes web/i18n.js from the apps' String Catalog (which also holds the few strings only the web reader uses), so
the web and the apps say the same thing in every language. Run after changing ios/Sources/Shared/Localizable.xcstrings."""
import json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
cat = json.loads((root / "ios/Sources/Shared/Localizable.xcstrings").read_text())
L = sorted({l for v in cat["strings"].values() for l in v["localizations"]})
table = {k: [v["localizations"].get(l, {}).get("stringUnit", {}).get("value", k) for l in L] for k, v in cat["strings"].items()}
js = f"""// Generated by scripts/gen_i18n.py from the apps' String Catalog; do not edit by hand.
// The reader is written in English. For a visitor whose browser asks for one of these languages, every text and label
// that exactly matches a key is swapped, now and as the reader adds more. Headlines never match a key.
(function () {{
  var langs = {json.dumps(L)};
  var pick = (navigator.languages || [navigator.language]).map(function (l) {{
    return /^zh-(hant|tw|hk|mo)/i.test(l) ? 'zh-Hant' : /^zh/i.test(l) ? 'zh-Hans' : /^pt/i.test(l) ? 'pt-BR' : l.slice(0, 2).toLowerCase();
  }}).find(function (l) {{ return langs.indexOf(l) >= 0; }});
  if (!pick) return;
  var col = langs.indexOf(pick), T = {json.dumps(table, ensure_ascii=False, separators=(',', ':'))};
  var one = function (s) {{ var k = s.trim(), row = T[k]; return row ? s.replace(k, row[col]) : s; }};
  // "Leans left · Canadian public broadcaster": each piece on its own
  var tr = function (s) {{ return s.indexOf(' · ') < 0 ? one(s) : s.split(' · ').map(one).join(' · '); }};
  function walk(root) {{
    var w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT), n;
    while ((n = w.nextNode())) {{ var v = tr(n.nodeValue); if (v !== n.nodeValue) n.nodeValue = v; }}
    if (root.querySelectorAll) [root].concat(Array.prototype.slice.call(root.querySelectorAll('[placeholder],[aria-label]'))).forEach(function (e) {{
      ['placeholder', 'aria-label'].forEach(function (a) {{ var v = e.getAttribute && e.getAttribute(a); if (v && tr(v) !== v) e.setAttribute(a, tr(v)); }});
    }});
  }}
  document.documentElement.lang = pick;
  if (pick === 'ar') document.documentElement.dir = 'rtl';
  walk(document.body);
  new MutationObserver(function (list) {{
    list.forEach(function (m) {{ m.addedNodes.forEach(function (n) {{ if (n.nodeType === 3) {{ var v = tr(n.nodeValue); if (v !== n.nodeValue) n.nodeValue = v; }} else if (n.nodeType === 1) walk(n); }}); }});
  }}).observe(document.body, {{ childList: true, subtree: true }});
}})();
"""
(root / "web/i18n.js").write_text(js)
print(len(table), "strings")
